#!/usr/bin/env node
// Derives the app's supported locales from messages/*.json and writes
// i18n/locales.generated.ts. Runs automatically before dev/build/typecheck/test
// (see package.json) so adding a new messages/<locale>.json file is enough to
// register that language everywhere — no other file needs to change.
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const messagesDir = path.join(process.cwd(), "messages");
const outFile = path.join(process.cwd(), "i18n", "locales.generated.ts");

const locales = readdirSync(messagesDir)
  .filter((file) => file.endsWith(".json"))
  .map((file) => file.replace(/\.json$/, ""))
  .sort();

if (locales.length === 0) {
  throw new Error(`No message files found in ${messagesDir}`);
}

const contents = `// Auto-generated by scripts/generate-locales.mjs — do not edit by hand.
// Regenerated from messages/*.json before every dev/build/typecheck/test run.
export const locales = [${locales.map((locale) => `"${locale}"`).join(", ")}] as const;
`;

writeFileSync(outFile, contents);
console.log(`generate-locales: [${locales.join(", ")}] -> i18n/locales.generated.ts`);
